"""
Kaaval Server Adapter (C1).
Handles events generated by centralized Kaaval GPU servers processing legacy DVR/NVR video streams.
"""
from __future__ import annotations

import uuid
from datetime import datetime, timezone
from typing import Dict, Any, Optional

from app.adapters.base import BaseAdapter
from app.schemas.event import (
    CanonicalEventEnvelope,
    SourceInfo,
    ProcessingProvenance,
    ObjectDetection,
)


class KaavalServerAdapter(BaseAdapter):
    @property
    def name(self) -> str:
        return "KAAVAL_SERVER"

    @property
    def protocol(self) -> str:
        return "KAAVAL_SERVER"

    def validate_payload(self, raw_payload: Dict[str, Any]) -> bool:
        if not isinstance(raw_payload, dict):
            return False
        return bool(raw_payload.get("event_id") or raw_payload.get("evt_id"))

    def normalize(
        self,
        raw_payload: Dict[str, Any],
        camera_id: str,
        processing_node_id: Optional[str] = None,
        context: Optional[Dict[str, Any]] = None,
    ) -> CanonicalEventEnvelope:
        source_evt_id = str(raw_payload.get("event_id") or raw_payload.get("evt_id") or uuid.uuid4())
        canonical_evt_id = f"evt-{uuid.uuid4().hex[:12]}"

        # Server timestamps are often ISO strings or ms
        raw_ts = raw_payload.get("timestamp") or raw_payload.get("ts_ms")
        if isinstance(raw_ts, (int, float)):
            event_ts = datetime.fromtimestamp(float(raw_ts) / 1000.0, tz=timezone.utc)
        elif isinstance(raw_ts, str):
            try:
                event_ts = datetime.fromisoformat(raw_ts.replace("Z", "+00:00"))
            except Exception:
                event_ts = datetime.now(timezone.utc)
        else:
            event_ts = datetime.now(timezone.utc)

        raw_type = str(raw_payload.get("event_type") or raw_payload.get("type", "ANALYTICS_ALERT")).upper()
        conf = float(raw_payload.get("confidence") or raw_payload.get("conf", 0.9))

        data = raw_payload.get("data") or raw_payload.get("attributes") or {}
        if not isinstance(data, dict):
            data = {}

        node_id = processing_node_id or raw_payload.get("server_id") or "KAAVAL-SERVER-AHM-001"
        model_version = str(raw_payload.get("model_version", "kaaval-server-v3.0"))

        return CanonicalEventEnvelope(
            event_id=canonical_evt_id,
            camera_id=camera_id,
            event_type=raw_type,
            timestamp=event_ts,
            source=SourceInfo(
                provider="KAAVAL_AI",
                adapter=self.name,
                source_event_id=source_evt_id,
            ),
            processing=ProcessingProvenance(
                processing_node_id=node_id,
                analytics_version="kaaval-server-suite-3.2",
                model_name=f"SERVER_{raw_type}",
                model_version=model_version,
                inference_fps=30.0,
                latency_ms=25.0,
            ),
            confidence=round(max(0.0, min(1.0, conf)), 4),
            object=ObjectDetection(
                type=data.get("object_type", "VEHICLE"),
                plate_number=data.get("plate") or data.get("plate_number"),
                vehicle_class=data.get("vehicle_class"),
                colour=data.get("colour"),
                bounding_box=data.get("bbox", []),
            ),
            attributes=data,
            evidence_ref={
                "image": f"mock://evidence/server/{source_evt_id}.jpg",
                "video": f"mock://evidence/server/{source_evt_id}.mp4",
            },
            delivery_status="DELIVERED",
        )

    def check_health(self, target_id: str) -> Dict[str, Any]:
        return {
            "adapter": self.name,
            "target": target_id,
            "status": "ONLINE",
            "protocol": self.protocol,
            "message": "Kaaval GPU server cluster healthy",
        }
